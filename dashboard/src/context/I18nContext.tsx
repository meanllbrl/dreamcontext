const PARTIALS: Record<string, Record<string, string>> = { tr: TR_PARTIAL };

interface I18nContextValue {
  locale: string;
  setLocale: (locale: string) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState('en');

  const t = (key: string): string => {
    return translations[locale]?.[key] ?? PARTIALS[locale]?.[key] ?? translations.en[key] ?? key;
  };

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

/** The explorer's copy follows its insight's locale, not the dashboard's: a card scopes its own. */
export type ScopedLocaleId = 'en' | 'tr';

/**
 * Re-provides the i18n context inside one subtree with `locale` fixed: the same
 * lookup chain (locale table, its partial, English, the key), and `setLocale`
 * still reaches the outer provider. A card whose insight speaks Turkish wraps
 * its blocks in this, so tabs, header, honesty copy and number formatting
 * (`useI18n().locale`) follow the card whatever the dashboard shows elsewhere.
 */
export function ScopedLocale({ locale, children }: { locale: ScopedLocaleId; children: ReactNode }) {
  const outer = useContext(I18nContext);
  const t = (key: string): string => translations[locale]?.[key] ?? PARTIALS[locale]?.[key] ?? translations.en[key] ?? key;
  const setLocale = outer?.setLocale ?? (() => {});
  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

/** The same context, or null outside a provider: for hooks shared with windows that may not
 *  mount one (the inline media pass runs in viewer windows too). */
export function useOptionalI18n(): I18nContextValue | null {
  return useContext(I18nContext);
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}

/**
 * The three machine-local task-system state files never reach a shared repo
 * (plan r4 R4-1; orchestrator additions 2-4).
 *
 * `state/.owner-corrections.json` holds the owner's own chat sentences,
 * `state/.learned-patterns.json` the learned-pattern history and
 * `state/.task-audit.json` the task audit. They are ignored:
 *   - in both governing .gitignore files BEFORE their first write, whatever
 *     shape those files have (absent, or made by other ensure blocks with no
 *     generated header, like this project's own brain);
 *   - in full-repo sync (`FULL_REPO_LOCAL_GITIGNORE_ENTRIES`, re-applied before
 *     every sync) and in the generated brain ignore;
 *   - by the 0.33.0 `local-state-ignore` step on every vault, which never throws.
 */
import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { ensureGitignoreEntries } from '../../src/lib/gitignore.js';
import { buildBrainGitignore, FULL_REPO_LOCAL_GITIGNORE_ENTRIES } from '../../src/lib/git-sync/brain-repo.js';
import { LOCAL_STATE_FILES, recordAudit } from '../../src/lib/task-audit.js';
import { ingestSessions } from '../../src/lib/owner-corrections.js';
import { migration0330 } from '../../src/migrations/0.33.0.js';

const FIX = join(__dirname, '..', 'fixtures', 'owner-corrections');
let projectRoot: string;
let ctx: string;

function ignored(rel: string): boolean {
  try {
    execFileSync('git', ['check-ignore', '-q', rel], { cwd: projectRoot, stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
}
const allIgnored = () => LOCAL_STATE_FILES.every((p) => ignored(`_dream_context/${p}`));
/** Run the 0.33.0 local-state-ignore step: the migration's last step, checked by its name. */
function runStep() {
  const r = migration0330.steps[migration0330.steps.length - 1](ctx);
  expect(r.step).toBe('local-state-ignore');
  return r;
}

beforeEach(() => {
  const raw = join(tmpdir(), `dc-local-ignore-${Date.now()}-${Math.random().toString(36).slice(2)}`);
  mkdirSync(raw, { recursive: true });
  projectRoot = realpathSync(raw);
  ctx = join(projectRoot, '_dream_context');
  mkdirSync(join(ctx, 'state'), { recursive: true });
  execFileSync('git', ['init', '-q'], { cwd: projectRoot });
});

afterEach(() => {
  rmSync(projectRoot, { recursive: true, force: true });
});

describe('ignored before the first write', () => {
  it('1. a vault with no _dream_context/.gitignore: the first recordAudit ignores all three paths', () => {
    expect(existsSync(join(ctx, '.gitignore'))).toBe(false);
    recordAudit(ctx, { kind: 'approval', slug: 't', actor: 'owner', via: 'dashboard', note: null, journalId: null });
    expect(allIgnored()).toBe(true);
  });

  it('2. a nested ignore made by ensureGitignoreEntries (no generated header): the first ingestSessions ignores all three', () => {
    ensureGitignoreEntries(ctx, ['automations/*.md'], { comment: 'dreamcontext automations — private by default' });
    expect(readFileSync(join(ctx, '.gitignore'), 'utf-8').startsWith('# Generated by dreamcontext.')).toBe(false);
    ingestSessions(ctx, [{ id: 's1-larkspur', path: join(FIX, 's1.jsonl') }], 'owner-fixture', 'epoch');
    expect(allIgnored()).toBe(true);
    expect(existsSync(join(ctx, 'state', '.owner-corrections.json'))).toBe(true);
  });

  it('5. a .gitignore that is a directory refuses the write: recordAudit and ingestSessions throw, nothing is written', () => {
    mkdirSync(join(ctx, '.gitignore'));
    expect(() => recordAudit(ctx, { kind: 'approval', slug: 't', actor: 'owner', via: 'cli', note: null, journalId: null })).toThrow();
    expect(() => ingestSessions(ctx, [{ id: 's1-larkspur', path: join(FIX, 's1.jsonl') }], 'owner-fixture', 'epoch')).toThrow();
    expect(existsSync(join(ctx, 'state', '.task-audit.json'))).toBe(false);
    expect(existsSync(join(ctx, 'state', '.owner-corrections.json'))).toBe(false);
  });
});

describe('the shared ignore lists', () => {
  it('3. FULL_REPO_LOCAL_GITIGNORE_ENTRIES carries the three _dream_context/state paths', () => {
    for (const p of LOCAL_STATE_FILES) expect(FULL_REPO_LOCAL_GITIGNORE_ENTRIES).toContain(`_dream_context/${p}`);
  });

  it('the generated brain ignore carries them above its first negation', () => {
    const lines = buildBrainGitignore('github').split('\n').map((l) => l.trim());
    const firstNegation = lines.findIndex((l) => l.startsWith('!'));
    for (const p of LOCAL_STATE_FILES) {
      const at = lines.indexOf(p);
      expect(at).toBeGreaterThan(-1);
      if (firstNegation >= 0) expect(at).toBeLessThan(firstNegation);
    }
  });
});

describe('4. the 0.33.0 local-state-ignore step', () => {
  it('adds the entries to a brain-shaped ignore (blank line, an automations block); a second run adds nothing; no line moves', () => {
    const before = '\n# dreamcontext automations — private by default\nautomations/*.md\n!automations/shared-digest.md\n';
    writeFileSync(join(ctx, '.gitignore'), before);
    const first = runStep();
    expect(first.detected).toBe(false);
    expect(first.failedCount ?? 0).toBe(0);
    const after = readFileSync(join(ctx, '.gitignore'), 'utf-8');
    expect(after.startsWith(before)).toBe(true);
    expect(allIgnored()).toBe(true);
    const second = runStep();
    expect(second.detected).toBe(true);
    expect(readFileSync(join(ctx, '.gitignore'), 'utf-8')).toBe(after);
  });

  it('never throws: a .gitignore that is a directory reports failedCount 1 with the error in the summary', () => {
    mkdirSync(join(ctx, '.gitignore'));
    const r = runStep();
    expect(r.failedCount).toBe(1);
    expect(r.summary).toMatch(/not a regular file/);
  });
});

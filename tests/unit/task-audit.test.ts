/**
 * The task audit (plan r3 § W2) and the ignore it stands behind (r4 R4-1,
 * orchestrator additions 1, 4).
 *
 * The audit lists every owner override and verdict with WHO and THROUGH WHAT.
 * It is machine-local: before its first write, `ensureLocalStateIgnored` puts
 * the three task-system state files in both governing `.gitignore` files, in
 * whatever shape those files are (absent, or made by another `ensureGitignoreEntries`
 * block with no generated header), and a `.gitignore` that cannot take the
 * entries refuses the write. Its atomic-write temp lives under the ignored
 * `_dream_context/tmp/`, never beside the file in `state/`.
 */
import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { ensureGitignoreEntries } from '../../src/lib/gitignore.js';
import {
  LOCAL_STATE_FILES,
  MAX_AUDIT_ENTRIES,
  AuditError,
  ensureLocalStateIgnored,
  listAudit,
  markAuditSeen,
  recordAudit,
  type NewAuditEntry,
} from '../../src/lib/task-audit.js';

let projectRoot: string;
let contextRoot: string;

const entry = (over: Partial<NewAuditEntry> = {}): NewAuditEntry => ({
  kind: 'approval', slug: 'some-task', actor: 'owner', via: 'dashboard', note: null, journalId: null, ...over,
});

/** `git check-ignore -q` from the project root: exit 0 means ignored. */
function ignored(rel: string): boolean {
  try {
    execFileSync('git', ['check-ignore', '-q', rel], { cwd: projectRoot, stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
}

function allIgnored(): boolean {
  return LOCAL_STATE_FILES.every((p) => ignored(`_dream_context/${p}`));
}

beforeEach(() => {
  const raw = join(tmpdir(), `dc-audit-${Date.now()}-${Math.random().toString(36).slice(2)}`);
  mkdirSync(raw, { recursive: true });
  projectRoot = realpathSync(raw);
  contextRoot = join(projectRoot, '_dream_context');
  mkdirSync(join(contextRoot, 'state'), { recursive: true });
  execFileSync('git', ['init', '-q'], { cwd: projectRoot });
});

afterEach(() => {
  rmSync(projectRoot, { recursive: true, force: true });
});

describe('ensureLocalStateIgnored', () => {
  it('a vault with no .gitignore at all: the first recordAudit ignores all three paths from the project root', () => {
    expect(existsSync(join(contextRoot, '.gitignore'))).toBe(false);
    expect(allIgnored()).toBe(false);
    recordAudit(contextRoot, entry());
    expect(allIgnored()).toBe(true);
    expect(existsSync(join(contextRoot, 'state', '.task-audit.json'))).toBe(true);
  });

  it('a nested ignore made by another ensureGitignoreEntries block (no generated header) gets the entries too', () => {
    ensureGitignoreEntries(contextRoot, ['automations/*.md'], { comment: 'dreamcontext automations — private by default' });
    const before = readFileSync(join(contextRoot, '.gitignore'), 'utf-8');
    expect(before.startsWith('# Generated by dreamcontext.')).toBe(false);
    recordAudit(contextRoot, entry());
    expect(allIgnored()).toBe(true);
    // the existing block keeps its place: the new lines are appended after it
    expect(readFileSync(join(contextRoot, '.gitignore'), 'utf-8').startsWith(before)).toBe(true);
  });

  it('returns the entries it added (both files), and nothing on a second call', () => {
    const added = ensureLocalStateIgnored(contextRoot);
    expect(added).toEqual([
      ...LOCAL_STATE_FILES,
      ...LOCAL_STATE_FILES.map((p) => `_dream_context/${p}`),
    ]);
    expect(ensureLocalStateIgnored(contextRoot)).toEqual([]);
  });

  it('a .gitignore that is a directory refuses the write: recordAudit throws and no audit file is written', () => {
    mkdirSync(join(contextRoot, '.gitignore'));
    expect(() => recordAudit(contextRoot, entry())).toThrow();
    expect(existsSync(join(contextRoot, 'state', '.task-audit.json'))).toBe(false);
  });

  it('markAuditSeen ensures the ignore as well', () => {
    const e = recordAudit(contextRoot, entry());
    rmSync(join(contextRoot, '.gitignore'));
    rmSync(join(projectRoot, '.gitignore'));
    markAuditSeen(contextRoot, e.id, 'owner', 'dashboard');
    expect(allIgnored()).toBe(true);
  });
});

describe('the audit file', () => {
  it('writes atomically through _dream_context/tmp/, leaving no temp in state/', () => {
    recordAudit(contextRoot, entry());
    recordAudit(contextRoot, entry({ kind: 'force', note: 'chore' }));
    expect(readdirSync(join(contextRoot, 'state')).filter((f) => f.includes('.tmp'))).toEqual([]);
    expect(readdirSync(join(contextRoot, 'tmp')).filter((f) => f.endsWith('.tmp'))).toEqual([]);
  });

  it('lists newest first, filters by kind, age and seen; markAuditSeen records actor and via', () => {
    const old = recordAudit(contextRoot, entry({ kind: 'accept', slug: 'old' }), new Date('2026-09-01T00:00:00.000Z'));
    const a = recordAudit(contextRoot, entry({ kind: 'approval', slug: 'a' }), new Date('2026-10-17T00:00:00.000Z'));
    const b = recordAudit(contextRoot, entry({ kind: 'held_open', slug: 'b', via: 'cli', actor: 'sync' }), new Date('2026-10-18T00:00:00.000Z'));
    const now = new Date('2026-10-18T12:00:00.000Z');
    expect(listAudit(contextRoot, { now }).map((e) => e.id)).toEqual([b.id, a.id, old.id]);
    expect(listAudit(contextRoot, { kinds: ['held_open'], now }).map((e) => e.id)).toEqual([b.id]);
    expect(listAudit(contextRoot, { sinceDays: 30, now }).map((e) => e.id)).toEqual([b.id, a.id]);
    const seen = markAuditSeen(contextRoot, b.id, 'owner', 'phone', now);
    expect(seen.seen).toEqual({ at: now.toISOString(), actor: 'owner', via: 'phone' });
    expect(listAudit(contextRoot, { kinds: ['held_open'], unseenOnly: true, now })).toEqual([]);
  });

  it('refuses an unknown kind, an unknown via and an unknown id', () => {
    expect(() => recordAudit(contextRoot, entry({ kind: 'bogus' as never }))).toThrow(AuditError);
    expect(() => recordAudit(contextRoot, entry({ via: 'curl' as never }))).toThrow(AuditError);
    expect(() => markAuditSeen(contextRoot, 'ta_missing0', 'owner', 'dashboard')).toThrow(AuditError);
  });

  it('keeps at most MAX_AUDIT_ENTRIES, dropping the oldest', () => {
    const p = join(contextRoot, 'state', '.task-audit.json');
    const many = Array.from({ length: MAX_AUDIT_ENTRIES }, (_, i) => ({
      id: `ta_old${String(i).padStart(5, '0')}`, at: '2026-10-01T00:00:00.000Z', kind: 'approval', slug: `t${i}`,
      actor: 'owner', via: 'dashboard', note: null, journalId: null,
    }));
    writeFileSync(p, JSON.stringify({ version: 1, entries: many }));
    const fresh = recordAudit(contextRoot, entry({ slug: 'newest' }));
    const all = listAudit(contextRoot);
    expect(all).toHaveLength(MAX_AUDIT_ENTRIES);
    expect(all[0].id).toBe(fresh.id);
    expect(all.some((e) => e.id === `ta_old${String(MAX_AUDIT_ENTRIES - 1).padStart(5, '0')}`)).toBe(false);
  });

  it('an unreadable file reads as empty rather than failing a read', () => {
    writeFileSync(join(contextRoot, 'state', '.task-audit.json'), '{not json');
    expect(listAudit(contextRoot)).toEqual([]);
  });
});

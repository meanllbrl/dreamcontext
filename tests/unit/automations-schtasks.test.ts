describe('resolveWindowsDispatcherTarget — the installing CLI wins', () => {
  const none = { whichCmd: () => null, exists: () => false };

  it('bakes the app bundle CLI when that is what is running', () => {
    expect(resolveWindowsDispatcherTarget(BIN, none).bin).toBe(BIN);
  });

  it('bakes the global CLI when that is what is running', () => {
    const g = 'C:\\Users\\me\\AppData\\Roaming\\npm\\node_modules\\dreamcontext\\dist\\index.js';
    expect(resolveWindowsDispatcherTarget(g, none).bin).toBe(g);
  });

  it('falls back to the global shim when the running entry is not a CLI (a test runner)', () => {
    const t = resolveWindowsDispatcherTarget('C:\\repo\\node_modules\\vitest\\worker.js', {
      whichCmd: () => 'C:\\Users\\me\\AppData\\Roaming\\npm\\dreamcontext.cmd',
      exists: () => true,
    });
    expect(t.bin).toBe('C:\\Users\\me\\AppData\\Roaming\\npm\\node_modules\\dreamcontext\\dist\\index.js');
    expect(t.shell).toBe(process.execPath);
  });

  it('resolves nothing when there is no CLI and no shim target', () => {
    expect(resolveWindowsDispatcherTarget(null, none).bin).toBeNull();
    expect(resolveWindowsDispatcherTarget(null, { whichCmd: () => 'C:\\npm\\dreamcontext.cmd', exists: () => false }).bin).toBeNull();
  });
});

describe('inspect / install / uninstall (fake Task Scheduler)', () => {
  const base = () => ({ home, logPath, runningBin: BIN });

  it('a fresh home reports nothing present', async () => {
    const { runner, calls } = fakeRunner();
    const check = await inspectWindowsDispatcher({ ...base(), runner });
    expect(check).toMatchObject({ plistPresent: false, wrapperPresent: false, bootstrapped: false, mismatch: false });
    expect(check.resolved.bin).toBe(BIN);
    expect(calls).toEqual([['schtasks', '/Query', '/TN', WINDOWS_TASK_NAME]]);
  });

  it('install writes the VBS and the UTF-16 XML, then registers the task', async () => {
    const { runner, calls } = fakeRunner({ queryOk: false, createOk: true });
    const res = await installWindowsDispatcher({ ...base(), runner });
    expect(res).toMatchObject({ wroteWrapper: true, wrotePlist: true, bootstrapped: true, method: 'schtasks' });
    const vbs = windowsDispatcherScriptPath(home);
    const xml = windowsDispatcherXmlPath(home);
    expect(decodeUtf16Bom(readFileSync(vbs))).toContain('automations tick --all');
    expect(decodeUtf16Bom(readFileSync(xml))).toContain('<Hidden>true</Hidden>');
    expect(calls).toContainEqual(['schtasks', '/Create', '/TN', WINDOWS_TASK_NAME, '/XML', xml, '/F']);
    // the re-inspect after writing sees both files as current
    expect(res.check).toMatchObject({ wrapperCurrent: true, plistCurrent: true });
  });

  it('is idempotent when everything is current and registered', async () => {
    await installWindowsDispatcher({ ...base(), runner: fakeRunner({ queryOk: false }).runner });
    const { runner, calls } = fakeRunner({ queryOk: true });
    const again = await installWindowsDispatcher({ ...base(), runner });
    expect(again).toMatchObject({ wroteWrapper: false, wrotePlist: false, bootstrapped: true, method: 'none' });
    expect(calls.some((c) => c[1] === '/Create')).toBe(false);
  });

  it('warns, never throws, when schtasks /Create fails', async () => {
    const res = await installWindowsDispatcher({ ...base(), runner: fakeRunner({ createOk: false }).runner });
    expect(res.method).toBe('none');
    expect(res.bootstrapped).toBe(false);
    expect(res.warnings[0]).toMatch(/schtasks \/Create failed: denied/);
  });

  it('refuses when no CLI resolves', async () => {
    // not a dist entry and no shim on the (emptied) PATH ⇒ nothing resolves
    await expect(
      installWindowsDispatcher({ home, logPath, runningBin: 'C:\\x\\worker.js', runner: fakeRunner().runner }),
    ).rejects.toThrow(AutomationError);
  });

  it('a changed target makes the installed script stale', async () => {
    await installWindowsDispatcher({ ...base(), runner: fakeRunner().runner });
    const moved = await inspectWindowsDispatcher({
      home, logPath, runningBin: 'C:\\Elsewhere\\dreamcontext-beta\\dist\\index.js', runner: fakeRunner({ queryOk: true }).runner,
    });
    expect(moved.wrapperCurrent).toBe(false);
  });

  it('uninstall deletes the task and both files; safe when nothing was installed', async () => {
    await installWindowsDispatcher({ ...base(), runner: fakeRunner().runner });
    const { runner, calls } = fakeRunner();
    const out = await uninstallWindowsDispatcher({ home, runner });
    expect(out).toEqual({ bootedOut: true, removedPlist: true, removedWrapper: true });
    expect(calls).toEqual([['schtasks', '/Delete', '/TN', WINDOWS_TASK_NAME, '/F']]);
    expect(existsSync(windowsDispatcherScriptPath(home))).toBe(false);

    const none = await uninstallWindowsDispatcher({ home, runner: fakeRunner({ deleteOk: false }).runner });
    expect(none).toEqual({ bootedOut: false, removedPlist: false, removedWrapper: false });
  });
});

describe('launchd.ts delegates to schtasks on win32', () => {
  const orig = process.platform;
  beforeEach(() => { Object.defineProperty(process, 'platform', { value: 'win32', configurable: true }); });
  afterEach(() => { Object.defineProperty(process, 'platform', { value: orig, configurable: true }); });

  it('uninstallDispatcher talks to schtasks, never launchctl', async () => {
    const { runner, calls } = fakeRunner();
    await uninstallDispatcher({ home, runner });
    expect(calls.map((c) => c[0])).toEqual(['schtasks']);
  });

  it('installDispatcher registers through schtasks and reports method "schtasks"', async () => {
    const { runner, calls } = fakeRunner();
    // Under vitest argv[1] is not a dist entry and the PATH is empty, so nothing resolves and the
    // install refuses by name — through the Windows path, so launchctl is never touched.
    await expect(installDispatcher({ home, runner, force: true })).rejects.toThrow(/dreamcontext CLI/);
    expect(calls.every((c) => c[0] === 'schtasks')).toBe(true);
  });
});

describe('a non-ASCII profile path (WSH reads a BOM-less .vbs as the ANSI code page)', () => {
  const turkish = 'C:\\Users\\Öğretmen\\AppData\\Local\\dreamcontext-beta\\dist\\index.js';

  it('the installed VBS is UTF-16LE with a BOM and decodes back to the exact path', async () => {
    const res = await installWindowsDispatcher({ home, logPath, runningBin: turkish, runner: fakeRunner().runner });
    expect(res.wroteWrapper).toBe(true);
    const bytes = readFileSync(windowsDispatcherScriptPath(home));
    expect([bytes[0], bytes[1]]).toEqual([0xff, 0xfe]);
    expect(decodeUtf16Bom(bytes)).toContain(turkish);
    // read back by inspect, with the generatedAt regex still matching
    expect(res.check.wrapperCurrent).toBe(true);
  });

  it.runIf(process.platform === 'win32')('real wscript.exe runs it from a directory named with Ö and writes the log', () => {
    const dir = mkdtempSync(join(tmpdir(), 'dc-Özel-'));
    try {
      mkdirSync(join(dir, 'dist'));
      const cli = join(dir, 'dist', 'index.js');
      writeFileSync(cli, "console.log('TICK ' + process.argv.slice(2).join(' '))");
      const log = join(dir, 'out.log');
      const vbs = join(dir, 'x.vbs');
      writeFileSync(vbs, encodeUtf16Bom(renderWindowsDispatcherScript({ bin: cli, path: '', shell: process.execPath }, log, 't')));
      const r = spawnSync(join(process.env.SystemRoot ?? 'C:\\Windows', 'System32', 'wscript.exe'), ['//B', '//Nologo', vbs], { timeout: 30_000 });
      expect({ status: r.status, signal: r.signal, error: r.error?.message }).toEqual({ status: 0, signal: null, error: undefined });
      expect(readFileSync(log, 'utf-8')).toContain('TICK automations tick --all');
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});

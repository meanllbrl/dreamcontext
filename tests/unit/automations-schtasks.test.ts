/** Records every call; `schtasks /Query` answers `queryOk`, everything else `createOk`. */
function fakeRunner(opts: { queryOk?: boolean; createOk?: boolean; deleteOk?: boolean } = {}): { runner: ExecRunner; calls: string[][] } {
  const calls: string[][] = [];
  const runner: ExecRunner = async (file, args) => {
    calls.push([file, ...args]);
    const ok = args[0] === '/Query' ? opts.queryOk ?? false
      : args[0] === '/Delete' ? opts.deleteOk ?? true
        : opts.createOk ?? true;
    return { ok, stdout: '', stderr: ok ? '' : 'denied', code: ok ? 0 : 1 };
  };
  return { runner, calls };
}

describe('renderWindowsDispatcherScript', () => {
  it('is pure and runs the baked node + CLI hidden through cmd', () => {
    const a = renderWindowsDispatcherScript(target, logPath, '2026-10-16T00:00:00.000Z');
    expect(renderWindowsDispatcherScript(target, logPath, '2026-10-16T00:00:00.000Z')).toBe(a);
    expect(a).toContain("' Generated by `dreamcontext automations install` at 2026-10-16T00:00:00.000Z.");
    // window style 0 (hidden), wait = True
    expect(a).toMatch(/\.Run ".*", 0, True\r\n$/);
    // every quote of the cmd line (the outer pair for /s, and the three quoted paths) is doubled inside the VBS literal
    expect(a).toContain(`cmd.exe /d /s /c """"${NODE}"" ""${BIN}"" automations tick --all >> ""${logPath}"" 2>&1"""`);
  });

  it('refuses a path cmd or VBS would reinterpret', () => {
    expect(() => renderWindowsDispatcherScript({ ...target, bin: 'C:\\100%\\x.js' }, logPath, 't')).toThrow(AutomationError);
    expect(() => renderWindowsDispatcherScript({ ...target, bin: 'C:\\a"b\\x.js' }, logPath, 't')).toThrow(AutomationError);
  });

  it('with nothing resolved only logs why', () => {
    const a = renderWindowsDispatcherScript({ ...target, bin: null }, logPath, 't');
    expect(a).toContain('not resolved');
    expect(a).not.toContain('automations tick');
  });
});

describe('renderWindowsTaskXml', () => {
  it('is hidden, non-overlapping, every 5 minutes, and launches the VBS through wscript', () => {
    const xml = renderWindowsTaskXml('C:\\Users\\me\\.dreamcontext\\bin\\automations-dispatch.vbs');
    expect(xml).toContain('<Interval>PT5M</Interval>');
    expect(xml).toContain('<Hidden>true</Hidden>');
    expect(xml).toContain('<MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>');
    expect(xml).toContain('<LogonType>InteractiveToken</LogonType>');
    expect(xml).toContain('<Command>wscript.exe</Command>');
    expect(xml).toContain('//B //Nologo &quot;C:\\Users\\me\\.dreamcontext\\bin\\automations-dispatch.vbs&quot;');
  });

  it('escapes XML metacharacters in the script path', () => {
    const xml = renderWindowsTaskXml('C:\\a&b\\<x>.vbs');
    expect(xml).toContain('a&amp;b');
    expect(xml).toContain('&lt;x&gt;');
  });

  it('is deterministic', () => {
    expect(renderWindowsTaskXml('C:\\s.vbs')).toBe(renderWindowsTaskXml('C:\\s.vbs'));
  });
});


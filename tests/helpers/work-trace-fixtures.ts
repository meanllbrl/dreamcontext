/**
 * Transcript fixtures for a member's past work (plan uye-gecmis-is): Claude's record shapes, the
 * Codex rollout the converter reads, and Antigravity's string-content lines. Every word is
 * fictional (pattern synthetic-fixtures): the owner is Deniz Kaya, the products kestrel, lumen and
 * fjord, the members mira and oren.
 */
import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

type Rec = Record<string, unknown>;

export const T0 = Date.parse('2026-11-20T10:00:00.000Z');

let uid = 0;
const nextUuid = (): string => {
  uid += 1;
  return `00000000-0000-4000-8000-${String(uid).padStart(12, '0')}`;
};

/** A Claude transcript built record by record (each call advances the clock one second). */
export class Tx {
  recs: Rec[] = [];
  t: number;
  constructor(start: number = T0) { this.t = start; }
  private ts(): string { this.t += 1000; return new Date(this.t).toISOString(); }
  push(r: Rec): this { this.recs.push(r); return this; }
  /** A user prompt record (first text block), with any record fields. */
  user(text: string, extra: Rec = {}): this {
    return this.push({ type: 'user', uuid: nextUuid(), timestamp: this.ts(), message: { role: 'user', content: [{ type: 'text', text }] }, ...extra });
  }
  /** A user prompt with string content (Claude SDK, converters). */
  userStr(text: string, extra: Rec = {}): this {
    return this.push({ type: 'user', uuid: nextUuid(), timestamp: this.ts(), message: { role: 'user', content: text }, ...extra });
  }
  image(): this {
    return this.push({ type: 'user', uuid: nextUuid(), timestamp: this.ts(), message: { role: 'user', content: [{ type: 'image', source: { type: 'base64', media_type: 'image/png', data: 'AAAA' } }] } });
  }
  say(text: string): this {
    return this.push({ type: 'assistant', uuid: nextUuid(), timestamp: this.ts(), message: { role: 'assistant', content: [{ type: 'text', text }] } });
  }
  think(): this {
    return this.push({ type: 'assistant', uuid: nextUuid(), timestamp: this.ts(), message: { role: 'assistant', content: [{ type: 'thinking', thinking: 'hmm' }] } });
  }
  refusal(): this {
    return this.push({ type: 'assistant', uuid: nextUuid(), timestamp: this.ts(), isApiErrorMessage: true, message: { role: 'assistant', content: [{ type: 'text', text: 'API Error: usage limit reached' }] } });
  }
  /** A tool call with its result. */
  tool(name: string, input: Rec): this {
    const id = `toolu_${nextUuid().slice(-8)}`;
    this.push({ type: 'assistant', uuid: nextUuid(), timestamp: this.ts(), message: { role: 'assistant', content: [{ type: 'tool_use', id, name, input }] } });
    return this.push({ type: 'user', uuid: nextUuid(), timestamp: this.ts(), toolUseResult: { ok: true }, message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: id, content: 'ok' }] } });
  }
  write(path: string): this { return this.tool('Write', { file_path: path, content: 'x' }); }
  edit(path: string): this { return this.tool('Edit', { file_path: path, old_string: 'a', new_string: 'b' }); }
  bash(command: string): this { return this.tool('Bash', { command }); }
  /** A tool call that never got its result (cut off). */
  toolCut(name = 'Bash'): this {
    return this.push({ type: 'assistant', uuid: nextUuid(), timestamp: this.ts(), message: { role: 'assistant', content: [{ type: 'tool_use', id: 'toolu_cut', name, input: { command: 'sleep 99' } }] } });
  }
  interrupt(): this {
    return this.push({ type: 'user', uuid: nextUuid(), timestamp: this.ts(), message: { role: 'user', content: [{ type: 'text', text: '[Request interrupted by user]' }] } });
  }
  /** A local command (`/effort`, `/clear`, `/model`): its stub, then only its stdout. */
  local(name: string, out = ''): this {
    this.user(`<command-name>/${name}</command-name>\n<command-message>${name}</command-message>\n<command-args></command-args>`);
    return this.push({ type: 'user', uuid: nextUuid(), timestamp: this.ts(), message: { role: 'user', content: `<local-command-stdout>${out}</local-command-stdout>` } });
  }
  caveat(): this {
    return this.push({ type: 'user', uuid: nextUuid(), timestamp: this.ts(), isMeta: true, message: { role: 'user', content: '<local-command-caveat>Caveat: the messages below were generated by the user while running local commands.</local-command-caveat>' } });
  }
  /** A skill command with arguments: the stub, then its isMeta skill body. */
  skill(name: string, args: string): this {
    this.user(`<command-message>${name}</command-message>\n<command-name>/${name}</command-name>\n<command-args>${args}</command-args>`);
    return this.push({ type: 'user', uuid: nextUuid(), timestamp: this.ts(), isMeta: true, message: { role: 'user', content: [{ type: 'text', text: `Base directory for this skill: /fictional/skills/${name}\n\n# ${name}` }] } });
  }
  meta(text: string): this {
    return this.push({ type: 'user', uuid: nextUuid(), timestamp: this.ts(), isMeta: true, message: { role: 'user', content: [{ type: 'text', text }] } });
  }
  /** A background task notification the harness injects. */
  notification(): this {
    return this.push({ type: 'user', uuid: nextUuid(), timestamp: this.ts(), turnOrigin: 'task_notification', message: { role: 'user', content: '<task-notification><task-id>b1</task-id><status>completed</status></task-notification>' } });
  }
  /** A folded steer (typed while the agent worked). */
  steer(text: string): this {
    return this.push({ type: 'attachment', uuid: nextUuid(), timestamp: this.ts(), attachment: { type: 'queued_command', prompt: text } });
  }
  compactSummary(): this {
    return this.push({ type: 'user', uuid: nextUuid(), timestamp: this.ts(), isCompactSummary: true, message: { role: 'user', content: 'This session is being continued from a previous conversation.' } });
  }
  sidechain(text: string): this {
    return this.push({ type: 'user', uuid: nextUuid(), timestamp: this.ts(), isSidechain: true, message: { role: 'user', content: text } });
  }
  jsonl(): string { return this.recs.map((r) => JSON.stringify(r)).join('\n') + '\n'; }
}

/** The same exchange as Antigravity's bridge writes it: string content, no uuid. */
export function asStringContent(tx: Tx): string {
  return tx.recs.map((r) => {
    const { uuid: _u, ...rest } = r as Rec & { uuid?: string };
    const m = rest.message as { role?: string; content?: unknown } | undefined;
    if (rest.type === 'user' && m && Array.isArray(m.content) && m.content.length === 1 && (m.content[0] as Rec).type === 'text') {
      return JSON.stringify({ ...rest, message: { role: 'user', content: (m.content[0] as { text: string }).text } });
    }
    return JSON.stringify(rest);
  }).join('\n') + '\n';
}

/** A Codex rollout: owner text items, assistant messages and an apply_patch call. */
export class Rollout {
  lines: string[] = [];
  t: number;
  constructor(start: number = T0) { this.t = start; }
  private ts(): string { this.t += 1000; return new Date(this.t).toISOString(); }
  user(text: string): this {
    this.lines.push(JSON.stringify({ timestamp: this.ts(), type: 'response_item', payload: { type: 'message', role: 'user', content: [{ type: 'input_text', text }], internal_chat_message_metadata_passthrough: { content_item_kinds: ['user.text'] } } }));
    return this;
  }
  injected(text: string): this {
    this.lines.push(JSON.stringify({ timestamp: this.ts(), type: 'response_item', payload: { type: 'message', role: 'user', content: [{ type: 'input_text', text }] } }));
    return this;
  }
  say(text: string): this {
    this.lines.push(JSON.stringify({ timestamp: this.ts(), type: 'response_item', payload: { type: 'message', role: 'assistant', content: [{ type: 'output_text', text }] } }));
    return this;
  }
  patch(file: string): this {
    this.lines.push(JSON.stringify({ timestamp: this.ts(), type: 'response_item', payload: { type: 'custom_tool_call', name: 'apply_patch', input: `*** Begin Patch\n*** Add File: ${file}\n+x\n*** End Patch` } }));
    return this;
  }
  text(): string { return this.lines.join('\n') + '\n'; }
}

// ─── A fake machine: HOME, projects, members ───────────────────────────────

export interface Machine {
  root: string;
  home: string;
  project: (name: string) => string;
  dispose: () => void;
}

/** A fake HOME with the named projects (each a `_dream_context/`). Nothing is spawned. */
export function makeMachine(projects: string[] = ['kestrel', 'lumen', 'fjord']): Machine {
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'past-work-')));
  const home = join(root, 'home');
  mkdirSync(join(home, '.dreamcontext'), { recursive: true });
  for (const p of projects) mkdirSync(join(root, p, '_dream_context', 'agents'), { recursive: true });
  return {
    root, home,
    project: (n) => join(root, n),
    dispose: () => { try { rmSync(root, { recursive: true, force: true }); } catch { /* best effort */ } },
  };
}

/** A global member: its file only (no home folder, as `agents create --scope global` leaves it). */
export function globalMember(m: Machine, slug: string): void {
  mkdirSync(join(m.home, '.dreamcontext', 'agents'), { recursive: true });
  writeFileSync(join(m.home, '.dreamcontext', 'agents', `${slug}.md`), `---\nname: ${slug}\ntitle: ${slug}\n---\nA fictional member.\n`);
}

/** A project member of one project. */
export function projectMember(m: Machine, project: string, slug: string): void {
  writeFileSync(join(m.project(project), '_dream_context', 'agents', `${slug}.md`), `---\nname: ${slug}\ntitle: ${slug}\n---\nA fictional member.\n`);
}

/** Write a Claude transcript where the locator finds it. Returns its path. */
export function putClaude(m: Machine, id: string, text: string, dir = '-fictional-project'): string {
  const d = join(m.home, '.claude', 'projects', dir);
  mkdirSync(d, { recursive: true });
  const p = join(d, `${id}.jsonl`);
  writeFileSync(p, text);
  return p;
}

/** Write an Antigravity bridge transcript. */
export function putAntigravity(m: Machine, id: string, text: string): string {
  const d = join(m.home, '.dreamcontext', 't3', 'transcripts');
  mkdirSync(d, { recursive: true });
  const p = join(d, `${id}.jsonl`);
  writeFileSync(p, text);
  return p;
}

/** Write a Codex rollout under `~/.codex/sessions/2026/11/20/`. */
export function putCodex(m: Machine, threadId: string, text: string): string {
  const d = join(m.home, '.codex', 'sessions', '2026', '11', '20');
  mkdirSync(d, { recursive: true });
  const p = join(d, `rollout-2026-11-20T10-00-00-${threadId}.jsonl`);
  writeFileSync(p, text);
  return p;
}

import { createHash } from 'node:crypto';
import { MAC_SURFACE_HEADER } from '../lib/handsfree/mac/contract.js';

/**
 * Hands-free Mac mode's service worker, served at `/handsfree-sw.js` on the phone listener by
 * `handsfree-login.ts` and registered by the phone's chat surface (phoneState.ts).
 *
 *  - A response carrying our `X-Dreamcontext-Surface: mac` passes through untouched, whatever
 *    its status: the Mac answered.
 *  - Only a 404/502/503/504/530 or a network error WITHOUT our header means "the Mac is not
 *    reachable" (the tunnel's edge answers those when the Mac is off), and only after retries.
 *  - Only the offline page is cached (install time, versioned, old caches deleted).
 *  - Never /api/*, /login, the WebSocket or assets: only top-level navigations.
 *  - A push is always shown (iOS revokes a subscription whose pushes show nothing); a tap opens
 *    the push's own chat link, same-origin paths only.
 */

export const SURFACE_HEADER = MAC_SURFACE_HEADER;
export const OFFLINE_PATH = '/handsfree-offline.html';
export const SW_PATH = '/handsfree-sw.js';
/** Per-attempt timeouts: one try plus two retries. */
export const ATTEMPT_TIMEOUTS_MS: readonly number[] = [8000, 5000, 5000];

export type SwVerdict = 'pass' | 'retry' | 'offline';

export interface SwAttempt {
  /** 1-based attempt number. */
  attempt: number;
  maxAttempts: number;
  /** null for a network error (fetch threw, or the attempt timed out). */
  status: number | null;
  /** The response carried `X-Dreamcontext-Surface: mac`. */
  hasSurfaceHeader: boolean;
}

/**
 * Pure: what the SW does with one attempt's outcome. Self-contained on purpose: its source is
 * embedded verbatim into the service worker script (no imports, no outer constants).
 */
export function swDecide(a: SwAttempt): SwVerdict {
  if (a.status !== null && a.hasSurfaceHeader) return 'pass';
  const asleep = a.status === null || a.status === 404 || a.status === 502 || a.status === 503 || a.status === 504 || a.status === 530;
  if (!asleep) return 'pass';
  return a.attempt < a.maxAttempts ? 'retry' : 'offline';
}

/** Pure: does the SW handle this request at all? Only same-origin top-level navigations. */
export function swIntercepts(mode: string, url: string, origin: string): boolean {
  if (mode !== 'navigate') return false;
  let u: URL;
  try { u = new URL(url); } catch { return false; }
  if (u.origin !== origin) return false;
  const p = u.pathname;
  if (p === '/api' || p.startsWith('/api/')) return false;
  if (p === '/login' || p.startsWith('/login/')) return false;
  if (p === '/handsfree-sw.js' || p === '/handsfree-offline.html' || p === '/manifest.webmanifest') return false;
  return true;
}

/** Pure: where a notification tap may land. Only a same-origin path (the push's own D10 link);
 *  anything else, or nothing, lands on `/`. Self-contained: embedded verbatim into the SW. */
export function swLandingUrl(url: unknown, origin: string): string {
  if (typeof url !== 'string' || !url.startsWith('/') || url.startsWith('//')) return '/';
  let u: URL;
  try { u = new URL(url, origin); } catch { return '/'; }
  return u.origin === origin && !u.pathname.startsWith('//') ? u.pathname + u.search : '/';
}

/** The service worker script. `version` names the cache (the offline page's hash). */
export function serviceWorkerSource(version: string): string {
  return `// dreamcontext hands-free service worker. Generated by the Mac's phone listener.
'use strict';
const CACHE = ${JSON.stringify(`dc-hf-offline-${version}`)};
const OFFLINE = ${JSON.stringify(OFFLINE_PATH)};
const SURFACE = ${JSON.stringify(SURFACE_HEADER)};
const TIMEOUTS = ${JSON.stringify(ATTEMPT_TIMEOUTS_MS)};
const decide = (${swDecide.toString()});
const intercepts = (${swIntercepts.toString()});
const landingUrl = (${swLandingUrl.toString()});

async function attempt(url, accept, timeoutMs) {
  const ctl = new AbortController();
  const timer = setTimeout(() => ctl.abort(), timeoutMs);
  try {
    const headers = {};
    if (accept) headers.Accept = accept;
    // redirect 'manual': a navigation may only be answered with an unfollowed redirect.
    return await fetch(url, { headers, credentials: 'include', cache: 'no-store', redirect: 'manual', signal: ctl.signal });
  } catch {
    return null;
  } finally {
    clearTimeout(timer);
  }
}

async function navigate(request) {
  const accept = request.headers.get('Accept') || 'text/html';
  let last = null;
  for (let i = 1; i <= TIMEOUTS.length; i++) {
    const res = await attempt(request.url, accept, TIMEOUTS[i - 1]);
    if (res) last = res;
    const verdict = decide({
      attempt: i,
      maxAttempts: TIMEOUTS.length,
      status: res ? res.status : null,
      hasSurfaceHeader: !!(res && res.headers.get(SURFACE) === 'mac'),
    });
    if (verdict === 'pass') return res;
    if (verdict === 'offline') break;
    await new Promise((r) => setTimeout(r, 400 * i));
  }
  const cached = await caches.match(OFFLINE, { cacheName: CACHE });
  return cached || last || Response.error();
}

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    for (let i = 0; i < 3; i++) {
      const res = await attempt(OFFLINE, '*/*', 10000);
      if (res && res.ok && res.headers.get(SURFACE) === 'mac') { await cache.put(OFFLINE, res); return; }
      await new Promise((r) => setTimeout(r, 1000 * (i + 1)));
    }
    throw new Error('offline page unavailable');
  })());
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key !== CACHE) await caches.delete(key);
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const r = event.request;
  if (!intercepts(r.mode, r.url, self.location.origin)) return;
  event.respondWith(navigate(r));
});

// Push: ALWAYS show what arrives (iOS revokes a subscription whose pushes show nothing); the
// server already skipped a phone that has this chat on screen.
self.addEventListener('push', (event) => {
  let p = {};
  try { p = event.data ? event.data.json() : {}; } catch { p = {}; }
  const title = typeof p.title === 'string' && p.title ? p.title : 'dreamcontext';
  const url = landingUrl(p.url, self.location.origin);
  event.waitUntil(self.registration.showNotification(title, {
    body: typeof p.body === 'string' ? p.body : '',
    tag: String(p.conversationId || 'dreamcontext') + ':' + String(p.kind || ''),
    icon: '/icons/icon-192.png',
    badge: '/icons/icon-192.png',
    data: { url },
  }));
});

// A tap opens that chat: an open app window is focused and sent there, else one opens.
self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const url = landingUrl(event.notification.data && event.notification.data.url, self.location.origin);
  event.waitUntil((async () => {
    const wins = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    for (const w of wins) {
      if (new URL(w.url).origin !== self.location.origin) continue;
      try { await w.focus(); } catch {}
      try { await w.navigate(url); return; } catch {}
    }
    await self.clients.openWindow(url);
  })());
});
`;
}

/** A short content hash, used to version the offline cache. */
export function shortHash(...parts: string[]): string {
  const h = createHash('sha256');
  for (const p of parts) h.update(p).update('\0');
  return h.digest('hex').slice(0, 12);
}

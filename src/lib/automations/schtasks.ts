import { existsSync, mkdirSync, readFileSync, realpathSync, renameSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, win32 } from 'node:path';
import { homedir } from 'node:os';
import { randomBytes } from 'node:crypto';
import { AutomationError, TICK_INTERVAL_SECONDS } from './types.js';
import { whichOnPathWin32 } from '../claude-path.js';
// Types only: launchd.ts delegates to this module on win32, so a runtime import back would be a cycle.
import type { DispatcherTarget, ExecRunner, InstallCheck, InstallResult } from './launchd.js';

/**
 * The Windows dispatcher — the Task Scheduler twin of launchd.ts. ONE per-user task,
 * `\dreamcontext\automations`, ticks every `TICK_INTERVAL_SECONDS` and runs
 * `dreamcontext automations tick --all` over every registered project.
 *
 * Nothing may ever flash a window. A task whose action is `node.exe` (a console program) opens a
 * visible console on every tick, and `<Hidden>` only hides the task from the Task Scheduler UI.
 * So the action is `wscript.exe //B //Nologo <script.vbs>` (a GUI-subsystem host, no console of its
 * own), and the script runs the real command through `WScript.Shell.Run(..., 0, True)`: window style
 * 0 is a hidden console that node, git and claude then inherit, and `True` makes the script wait,
 * so `MultipleInstancesPolicy=IgnoreNew` really does stop overlapping ticks.
 *
 * The baked `dreamcontext` is the CLI that INSTALLED the task (see
 * {@link resolveWindowsDispatcherTarget}), so ticks run the build the owner just turned the
 * scheduler on with — the app's bundled CLI from the Automations page — and never a stale global.
 *
 * Every `schtasks` call goes through the same injectable `ExecRunner` launchd.ts uses; tests must
 * NEVER invoke the real Task Scheduler.
 */

export const WINDOWS_TASK_NAME = 'dreamcontext\\automations';

// ─── Paths ────────────────────────────────────────────────────────────────────

export function windowsDispatcherScriptPath(home: string = homedir()): string {
  return join(home, '.dreamcontext', 'bin', 'automations-dispatch.vbs');
}

export function windowsDispatcherXmlPath(home: string = homedir()): string {
  return join(home, '.dreamcontext', 'bin', 'automations-dispatch.xml');
}

function safeRealpath(p: string): string {
  try {
    return realpathSync(p);
  } catch {
    return p;
  }
}

function atomicWrite(filePath: string, content: string | Buffer): void {
  mkdirSync(dirname(filePath), { recursive: true });
  const tmp = `${filePath}.${process.pid}.${randomBytes(6).toString('hex')}.tmp`;
  writeFileSync(tmp, content);
  renameSync(tmp, filePath);
}

function localRunningBin(): string | null {
  const argv1 = process.argv[1];
  return argv1 ? safeRealpath(argv1) : null;
}

// ─── Resolution ───────────────────────────────────────────────────────────────

const DIST_ENTRY_RE = /[\\/]dist[\\/]index\.js$/i;

/**
 * The `dreamcontext` the scheduler will run. The CLI doing the install wins whenever it is a real
 * `dist\index.js` — the app's bundled copy when the scheduler is turned on from the app, the global
 * install when it is run from a terminal — so the resolved target and the running CLI agree (no
 * false "mismatch") and a tick never runs a different build than the one that installed it. Only a
 * non-CLI entry (a test runner, `node -e`) falls back to the global `dreamcontext.cmd` shim.
 * `shell` carries the node.exe that runs it; the VBS bakes it in.
 */
export function resolveWindowsDispatcherTarget(
  runningBin: string | null = localRunningBin(),
  deps: { whichCmd?: () => string | null; exists?: (p: string) => boolean } = {},
): DispatcherTarget {
  const exists = deps.exists ?? existsSync;
  const base = { path: process.env.PATH ?? '', shell: process.execPath };
  if (runningBin && DIST_ENTRY_RE.test(runningBin)) return { bin: runningBin, ...base };
  const shim = (deps.whichCmd ?? (() => whichOnPathWin32(['dreamcontext.cmd'])))();
  if (shim) {
    const entry = win32.join(win32.dirname(shim), 'node_modules', 'dreamcontext', 'dist', 'index.js');
    if (exists(entry)) return { bin: entry, ...base };
  }
  return { bin: null, ...base };
}

// ─── Pure renderers ───────────────────────────────────────────────────────────

const GENERATED_AT_RE = /^' Generated by `dreamcontext automations install` at (.+)\.\r?$/m;

/** A VBScript string literal: wrapped in double quotes, every embedded one doubled. */
function vbsString(s: string): string {
  return '"' + s.replace(/"/g, '""') + '"';
}

/** A path that is safe inside the cmd line below: no `%` (expanded even inside quotes), no `"`, no line break. */
function checkedPath(p: string): string {
  if (/[%"\r\n]/.test(p)) {
    throw new AutomationError(`Cannot schedule a path containing %, a double quote or a line break: ${p}`);
  }
  return p;
}

/**
 * The VBS the task runs (`wscript //B <script>`). PURE.
 *
 * The command is `cmd.exe /d /s /c "<inner>"`: `/s` strips exactly the outer pair of quotes, so
 * `inner` (three quoted paths and redirections) reaches cmd intact. `/d` skips AutoRun.
 * `bin: null` (nothing resolved) renders a script that only logs why nothing ran.
 */
export function renderWindowsDispatcherScript(target: DispatcherTarget, logPath: string, generatedAt: string): string {
  const log = checkedPath(logPath);
  const inner = target.bin === null
    ? `echo dispatcher: dreamcontext was not resolved when this task was installed >> "${log}" 2>&1`
    : `"${checkedPath(target.shell)}" "${checkedPath(target.bin)}" automations tick --all >> "${log}" 2>&1`;
  return [
    `' Generated by \`dreamcontext automations install\` at ${generatedAt}.`,
    "' Regenerate with: dreamcontext automations install",
    `CreateObject("WScript.Shell").Run ${vbsString(`cmd.exe /d /s /c "${inner}"`)}, 0, True`,
    '',
  ].join('\r\n');
}

function xmlEscape(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

/**
 * The Task Scheduler definition (`schtasks /Create /XML`). PURE. A fixed past `StartBoundary` keeps
 * the output deterministic (so "is the installed task current" is a string compare) and fires the
 * first tick as soon as the task is created. `InteractiveToken` runs it as the signed-in user with
 * no password; `Hidden` keeps it out of the default Task Scheduler view.
 */
export function renderWindowsTaskXml(scriptPath: string, intervalSeconds: number = TICK_INTERVAL_SECONDS): string {
  const interval = intervalSeconds % 60 === 0 ? `PT${intervalSeconds / 60}M` : `PT${intervalSeconds}S`;
  const args = xmlEscape(`//B //Nologo "${checkedPath(scriptPath)}"`);
  return `<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>dreamcontext automations dispatcher</Description>
  </RegistrationInfo>
  <Triggers>
    <TimeTrigger>
      <Repetition>
        <Interval>${interval}</Interval>
        <StopAtDurationEnd>false</StopAtDurationEnd>
      </Repetition>
      <StartBoundary>2026-01-01T00:00:00</StartBoundary>
      <Enabled>true</Enabled>
    </TimeTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>true</StartWhenAvailable>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>true</Hidden>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>wscript.exe</Command>
      <Arguments>${args}</Arguments>
    </Exec>
  </Actions>
</Task>
`;
}

/** `schtasks /XML` wants UTF-16 LE with a byte-order mark. */
export function encodeUtf16Bom(s: string): Buffer {
  return Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(s, 'utf16le')]);
}

export function decodeUtf16Bom(b: Buffer): string {
  const body = b.length >= 2 && b[0] === 0xff && b[1] === 0xfe ? b.subarray(2) : b;
  return body.toString('utf16le');
}

// ─── Inspect / install / uninstall ────────────────────────────────────────────

interface WinOpts {
  home: string;
  runner: ExecRunner;
  logPath: string;
  /** The CLI doing the install (`runningCliBin()`); read from argv[1] when omitted. */
  runningBin?: string | null;
}

/** Read-only: diffs what is on disk and in the Task Scheduler against what a fresh install would write. */
export async function inspectWindowsDispatcher(opts: WinOpts): Promise<InstallCheck> {
  const { home, runner, logPath } = opts;
  const runningBin = opts.runningBin === undefined ? localRunningBin() : opts.runningBin;
  const resolved = resolveWindowsDispatcherTarget(runningBin);
  const mismatch =
    resolved.bin !== null && runningBin !== null && safeRealpath(resolved.bin) !== safeRealpath(runningBin);

  const scriptPath = windowsDispatcherScriptPath(home);
  const xmlPath = windowsDispatcherXmlPath(home);

  const wrapperPresent = existsSync(scriptPath);
  let wrapperCurrent = false;
  if (wrapperPresent) {
    try {
      const onDisk = decodeUtf16Bom(readFileSync(scriptPath));
      const generatedAt = GENERATED_AT_RE.exec(onDisk)?.[1] ?? null;
      wrapperCurrent = generatedAt !== null && onDisk === renderWindowsDispatcherScript(resolved, logPath, generatedAt);
    } catch {
      wrapperCurrent = false;
    }
  }

  const plistPresent = existsSync(xmlPath);
  let plistCurrent = false;
  if (plistPresent) {
    try {
      plistCurrent = decodeUtf16Bom(readFileSync(xmlPath)) === renderWindowsTaskXml(scriptPath);
    } catch {
      plistCurrent = false;
    }
  }

  const bootstrapped = (await runner('schtasks', ['/Query', '/TN', WINDOWS_TASK_NAME])).ok;

  let logSizeBytes = 0;
  try {
    logSizeBytes = readFileSync(logPath).length;
  } catch {
    /* no log yet */
  }

  return { resolved, runningBin, mismatch, plistPresent, plistCurrent, wrapperPresent, wrapperCurrent, bootstrapped, logPath, logSizeBytes };
}

/** Same gates as launchd's `installDispatcher`: nothing resolved throws, a mismatch needs `force`, a current install is a no-op. */
export async function installWindowsDispatcher(opts: WinOpts & { force?: boolean }): Promise<InstallResult> {
  const { home, runner, logPath } = opts;
  const force = opts.force ?? false;
  const check = await inspectWindowsDispatcher(opts);
  const warnings: string[] = [];

  if (check.resolved.bin === null) {
    throw new AutomationError(
      'Could not find the dreamcontext CLI to schedule. Install it (npm i -g dreamcontext) or run this from the app, and try again.',
    );
  }
  if (check.mismatch && !force) {
    warnings.push(
      `Resolution mismatch: the scheduler would run "${check.resolved.bin}", but this install is ` +
        `running from "${check.runningBin}". Pass --force to install anyway, or re-run from the CLI ` +
        `you want the scheduler to use.`,
    );
    return { check, wroteWrapper: false, wrotePlist: false, bootstrapped: false, method: 'none', warnings };
  }
  if (check.mismatch && force) {
    warnings.push(`Resolution mismatch overridden with --force: installing to run "${check.resolved.bin}".`);
  }

  const alreadyCurrent =
    check.wrapperPresent && check.wrapperCurrent && check.plistPresent && check.plistCurrent && check.bootstrapped;
  if (alreadyCurrent && !force) {
    return { check, wroteWrapper: false, wrotePlist: false, bootstrapped: true, method: 'none', warnings };
  }

  const scriptPath = windowsDispatcherScriptPath(home);
  const xmlPath = windowsDispatcherXmlPath(home);
  mkdirSync(dirname(logPath), { recursive: true });
  // UTF-16LE + BOM, like the XML: WSH reads a BOM-less .vbs as the ANSI code page, which would turn
  // a non-ASCII profile path (C:\Users\Öğretmen) into mojibake inside the Run command.
  atomicWrite(scriptPath, encodeUtf16Bom(renderWindowsDispatcherScript(check.resolved, logPath, new Date().toISOString())));
  atomicWrite(xmlPath, encodeUtf16Bom(renderWindowsTaskXml(scriptPath)));

  const created = await runner('schtasks', ['/Create', '/TN', WINDOWS_TASK_NAME, '/XML', xmlPath, '/F']);
  if (!created.ok) warnings.push(`schtasks /Create failed: ${created.stderr || created.stdout}`);

  const finalCheck = await inspectWindowsDispatcher(opts);
  return {
    check: finalCheck,
    wroteWrapper: true,
    wrotePlist: true,
    bootstrapped: created.ok,
    method: created.ok ? 'schtasks' : 'none',
    warnings,
  };
}

/** Deletes the task, then the script and XML. Registry approvals are left untouched. */
export async function uninstallWindowsDispatcher(
  opts: { home: string; runner: ExecRunner },
): Promise<{ bootedOut: boolean; removedPlist: boolean; removedWrapper: boolean }> {
  const deleted = await opts.runner('schtasks', ['/Delete', '/TN', WINDOWS_TASK_NAME, '/F']);
  const drop = (p: string): boolean => {
    try {
      unlinkSync(p);
      return true;
    } catch {
      return false;
    }
  };
  return {
    bootedOut: deleted.ok,
    removedPlist: drop(windowsDispatcherXmlPath(opts.home)),
    removedWrapper: drop(windowsDispatcherScriptPath(opts.home)),
  };
}

/** The light theme's declarations in tokens.css (`:root`), `var()`s resolved. */
export function lightTokens(css: string): Record<string, string> {
  const clean = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const at = clean.indexOf(':root');
  const open = clean.indexOf('{', at);
  let depth = 0;
  let end = open;
  for (let i = open; i < clean.length; i++) {
    if (clean[i] === '{') depth++;
    else if (clean[i] === '}' && --depth === 0) { end = i; break; }
  }
  const out: Record<string, string> = {};
  for (const m of clean.slice(open + 1, end).matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) out[m[1]] = m[2].trim();
  const resolve = (v: string, d = 0): string => {
    const next = v.replace(/var\((--[\w-]+)\)/g, (w, n: string) => out[n] ?? w);
    return next === v || d > 20 ? next : resolve(next, d + 1);
  };
  for (const k of Object.keys(out)) out[k] = resolve(out[k]);
  return out;
}

/** The mark's colours, from the gem tokens. */
export function markColors(tokens: Record<string, string>): Record<HfPaint, string> {
  const out = {} as Record<HfPaint, string>;
  for (const [role, token] of Object.entries(HF_PAINT_TOKEN) as Array<[HfPaint, string]>) {
    const v = tokens[token];
    if (!v) throw new Error(`tokens.css has no ${token}`);
    out[role] = v;
  }
  return out;
}

export function buildSvgs(tokensCss: string): { mark: string; icon: string; iconOpaque: string; background: string } {
  const tokens = lightTokens(tokensCss);
  const colors = markColors(tokens);
  const background = tokens['--color-bg'];
  if (!background) throw new Error('tokens.css has no --color-bg');
  return {
    mark: `${handsfreeMarkSvg({ idPrefix: 'hf', box: 'mark', colors, title: 'dreamcontext hands-free' })}\n`,
    icon: `${handsfreeMarkSvg({ idPrefix: 'hf', box: 'icon', colors, title: 'dreamcontext hands-free' })}\n`,
    iconOpaque: handsfreeMarkSvg({ idPrefix: 'hf', box: 'icon', colors, background }),
    background,
  };
}

/** The server's mirror: three markup strings and their paint rules. */
export function buildServerMirror(): string {
  const mark = handsfreeMarkSvg({ idPrefix: 'hfl', box: 'mark', colors: null, className: 'hf-hero-mark', title: 'dreamcontext' });
  const decorA = handsfreeDecorSvg('hfm-decor hfm-decor--a');
  const decorB = handsfreeDecorSvg('hfm-decor hfm-decor--b');
  const q = (s: string) => JSON.stringify(s);
  return `// GENERATED by scripts/gen-handsfree-icons.ts from dashboard/src/components/brand/handsfreeMarkGeometry.ts.
// Do not edit: change the mark there and run \`npm run gen:handsfree-icons\`.
// tests/unit/handsfree-mark.test.ts fails when this file and the generator disagree.

/** The hands-free mark for the phone's server-rendered pages, painted by {@link HANDSFREE_MARK_CSS}. */
export const HANDSFREE_MARK_SVG = ${q(mark)};

/** The two gem outlines a phone page carries in its corners (painted by \`.hfm-decor-line\`). */
export const HANDSFREE_DECOR_SVG = ${q(decorA + decorB)};

/** The mark's paint rules: one per class, each a \`--gem-*\` token the page declares. */
export const HANDSFREE_MARK_CSS = ${q(handsfreePaintCss())};
`;
}


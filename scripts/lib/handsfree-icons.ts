const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();
function crc32(b: Buffer): number {
  let c = 0xffffffff;
  for (const x of b) c = CRC_TABLE[(c ^ x) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

/** The PNG with a `tEXt` chunk (`keyword\0text`) right after IHDR. */
export function withTextChunk(png: Buffer, keyword: string, text: string): Buffer {
  const ihdrEnd = 8 + 4 + 4 + png.readUInt32BE(8) + 4;
  const data = Buffer.from(`${keyword}\0${text}`, 'latin1');
  const typed = Buffer.concat([Buffer.from('tEXt', 'latin1'), data]);
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(typed));
  return Buffer.concat([png.subarray(0, ihdrEnd), len, typed, crc, png.subarray(ihdrEnd)]);
}


#!/bin/sh
# Regenerate the shipped-hash tables (run after any change to skill-draw/ or skill-design/).
set -e
cd "$(dirname "$0")/.."
{
  echo "// GENERATED by scripts/gen-guarded-tables.sh (scripts/gen-skill-shas.mjs). Append-only: every"
  echo "// version of every file a guarded core skill ever shipped, keyed by its path inside the skill."
  echo "// A copy with no recorded baseline (no manifest) is refreshed only when it matches one of these."
  echo ""
  echo "/** The old design pack (skill-packs/design) and the core skill since (skill-design). */"
  node scripts/gen-skill-shas.mjs skill-design --history skill-packs/design --name DESIGN_SHIPPED_SHAS
  echo ""
  echo "/** The draw skill (skill-draw) and, by the same path, the excalidraw pack it came from. */"
  node scripts/gen-skill-shas.mjs skill-draw --history skill-packs/excalidraw --map reference/=references/ --name DRAW_SHIPPED_SHAS
} > src/lib/core-guarded-skill/shipped.ts
{
  echo "// GENERATED by scripts/gen-guarded-tables.sh (scripts/gen-skill-shas.mjs). Append-only."
  echo "/** Every version of every file the retired excalidraw pack shipped, keyed by its path in the pack. */"
  node scripts/gen-skill-shas.mjs skill-packs/excalidraw --name EXCALIDRAW_SHIPPED_SHAS
} > src/lib/retired-packs/excalidraw.ts

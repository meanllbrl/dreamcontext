#!/bin/sh
# Regenerate the shipped-hash tables (run after any change to a guarded core skill: skill-design/,
# skill-draw/, skill-council/, skill-multi-review/, skill-goal-skill/, skill-video-watching/).
set -e
cd "$(dirname "$0")/.."
{
  echo "// GENERATED by scripts/gen-guarded-tables.sh (scripts/gen-skill-shas.mjs). Append-only: every"
  echo "// version of every file a guarded core skill ever shipped, keyed by its path inside the skill."
  echo "// A copy with no recorded baseline (no manifest) is refreshed only when it matches one of these."
  echo ""
  echo "/** The old design pack (skill-packs/design) and the core skill since (skill-design). */"
  node scripts/gen-skill-shas.mjs skill-design --history skill-packs/design --name DESIGN_SHIPPED_SHAS
  echo ""
  echo "/** The draw skill (skill-draw) and, by the same path, the excalidraw pack it came from. */"
  node scripts/gen-skill-shas.mjs skill-draw --history skill-packs/excalidraw --map reference/=references/ --name DRAW_SHIPPED_SHAS
  echo ""
  echo "/** council, multi-review, goal-skill, video-watching: optional packs until 2026-11-11, core since. */"
  node scripts/gen-skill-shas.mjs skill-council --history skill-packs/council --name COUNCIL_SHIPPED_SHAS
  echo ""
  node scripts/gen-skill-shas.mjs skill-multi-review --history skill-packs/multi-review --name MULTI_REVIEW_SHIPPED_SHAS
  echo ""
  node scripts/gen-skill-shas.mjs skill-goal-skill --history skill-packs/goal-skill --name GOAL_SKILL_SHIPPED_SHAS
  echo ""
  node scripts/gen-skill-shas.mjs skill-video-watching --history skill-packs/video-watching --name VIDEO_WATCHING_SHIPPED_SHAS
} > src/lib/core-guarded-skill/shipped.ts
{
  echo "// GENERATED by scripts/gen-guarded-tables.sh (scripts/gen-skill-shas.mjs). Append-only."
  echo "/** Every version of every file the retired excalidraw pack shipped, keyed by its path in the pack. */"
  node scripts/gen-skill-shas.mjs skill-packs/excalidraw --name EXCALIDRAW_SHIPPED_SHAS
} > src/lib/retired-packs/excalidraw.ts
{
  echo "// GENERATED by scripts/gen-guarded-tables.sh (scripts/gen-skill-shas.mjs). Append-only."
  echo "/** Every version of every agent that shipped in a pack and ships from agents/ since 2026-11-11, by file name. */"
  node scripts/gen-skill-shas.mjs agents --history skill-packs/agents --only reviewer.md --only review-router.md --only review-security.md --only review-cloud-functions.md --only review-frontend.md --only review-edge-cases.md --only goal-planner.md --only goal-plan-reviewer.md --only goal-implementer.md --only goal-validator.md --only council-persona.md --only council-synthesizer.md --name ADOPTED_AGENT_SHAS
} > src/lib/core-guarded-skill/adopted-agents.ts
{
  echo "// GENERATED by scripts/gen-guarded-tables.sh (scripts/gen-skill-shas.mjs). Append-only."
  echo "// The skills, agents and helper files dreamcontext stopped shipping on 2026-11-11, every version."
  for p in growth brand-voice business-idea-discovery business-idea-validation meta-marketing system-prompts jev-verify; do
    c=$(echo "$p" | tr 'a-z-' 'A-Z_')
    echo ""
    node scripts/gen-skill-shas.mjs skill-packs/$p --name "${c}_SHIPPED_SHAS"
  done
  echo ""
  echo "/** Agents of the stopped skills, by file name under .claude/agents/. */"
  node scripts/gen-skill-shas.mjs skill-packs/agents --only biv-customer-analyst.md --only biv-decision-gate.md --only biv-financial-analyst.md --only biv-market-analyst.md --only biv-researcher.md --only biv-strategist.md --only discover-brand.md --only marketing-creative.md --only marketing-monitor.md --only marketing-strategy.md --name STOPPED_AGENT_SHAS
  echo ""
  echo "/** goal-skill's helpers, installed at .claude/<name> until 2026-11-11 (now inside the skill's assets/). */"
  node scripts/gen-skill-shas.mjs skill-packs/goal-skill/assets --name GOAL_SKILL_OLD_ASSET_SHAS
  echo ""
  echo "/** Retired core agents with no manifest record to prove them ours, by file name: an unedited copy matches one of these. */"
  node scripts/gen-skill-shas.mjs skill-packs/agents --only review-coordinator.md --name RETIRED_CORE_AGENT_SHAS
} > src/lib/retired-packs/stopped.ts

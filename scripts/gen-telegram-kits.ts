#!/usr/bin/env -S npx vite-node
/**
 * Writes the server copies of the dashboard's sandboxed-frame kits, for the Telegram
 * picture builders (the server cannot import `dashboard/src`: rootDir is `src`):
 *
 *   src/lib/sandbox-font.ts          SANDBOX_FONT_CSS (the webfont that travels in every frame)
 *   src/lib/telegram/chat-kit.ts     the chat kit's constants + buildSandboxSrcdocServer,
 *                                    buildChatSrcdocServer (a dream-html block, as the chat
 *                                    draws it) and buildReportSrcdocServer (a report page, as
 *                                    `FrameViewer`'s `HtmlFrame` draws it)
 *   src/lib/telegram/lab-kit.ts      the Lab kit + buildLabSrcdocServer (an html/v1 insight)
 *   src/lib/telegram/kit-tokens.ts   the RESOLVED theme tokens each builder inlines
 *   src/lib/telegram/html-local-assets.ts  the page's own pictures and stylesheets written into
 *                                    it (`lib/htmlLocalAssets.ts` + `viewerPaths.ts`, copied as
 *                                    source: the Telegram PDF carries exactly what the card shows)
 *
 * It IMPORTS the dashboard modules and writes every constant as a literal, so nothing is
 * copied by hand. `tests/unit/telegram-kits.test.ts` builds fixed inputs with both sides and
 * requires byte-equal output, so a dashboard change fails the test until this script runs.
 *
 * Usage: npx vite-node scripts/gen-telegram-kits.ts   (or: npm run gen:telegram-kits)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import {
  CHAT_HTML_KIT_CSS, CHAT_KIT_TOKENS, HEIGHT_BRIDGE, KIT_BEHAVIOUR, REACH_BRIDGE,
} from '../dashboard/src/components/sleepy/chat/chatHtmlKit';
import { HTML_HEIGHT_BRIDGE, HTML_KIT_TOKENS, LAB_HTML_KIT_CSS } from '../dashboard/src/components/lab/labHtmlKit';
import { HOST_STYLE_ATTR, SANDBOX_ALLOW, SANDBOX_CSP, SANDBOX_FONT_CSS, SANDBOX_GRANT } from '../dashboard/src/lib/sandboxHtml';
import { SELECTION_BRIDGE } from '../dashboard/src/lib/textSelection';
import { LINK_GUARD } from '../dashboard/src/lib/htmlLocalAssets';
import { ZOOM_BRIDGE } from '../dashboard/src/components/layout/frameZoomBridge';
import { pageDefaultCss } from '../dashboard/src/lib/pageDefaultCss';
import { resolveTokensFromCss } from './telegram-kit-tokens';

const NON_ASCII = new RegExp('[\\u0080-\\uffff]', 'g');
/** A TS string literal, ASCII-only (non-ASCII escaped), so the source never depends on encoding. */
export const literalOf = (text: string): string => JSON.stringify(text).replace(
  NON_ASCII,
  (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`,
);

const HEADER = (from: string): string =>
  `// GENERATED by scripts/gen-telegram-kits.ts from ${from}. Do not edit by hand:\n` +
  `// run \`npm run gen:telegram-kits\`. Pinned by tests/unit/telegram-kits.test.ts.\n`;

const constant = (name: string, value: string, doc: string): string =>
  `/** ${doc} */\nexport const ${name} = ${literalOf(value)};\n`;

/** The chat pane's reading size and rhythm (`ChatPane.css` `.chat-pane`), pinned at zoom 1:
 *  a dream-html picture is set as the chat pane sets it, never at the Super stage's 17 px. */
export const CHAT_READING = { '--chat-text': '15px', '--chat-line-height': '1.75' } as const;

export function renderFont(): string {
  return HEADER('dashboard/src/lib/sandboxFont.ts') +
    '// About 300 KB of dist, accepted: a frame without its webfont sets text in a fallback face.\n' +
    constant('SANDBOX_FONT_CSS', SANDBOX_FONT_CSS, 'The @font-face rules every sandboxed frame carries inline.');
}

export function renderChatKit(): string {
  return `${HEADER('dashboard/src/lib/sandboxHtml.ts, chatHtmlKit.ts, reportSrcdoc.ts and their imports')}
import { SANDBOX_FONT_CSS } from '../sandbox-font.js';

${constant('SANDBOX_CSP', SANDBOX_CSP, 'The network-less CSP every sandboxed frame starts with.')}
${constant('HOST_STYLE_ATTR', HOST_STYLE_ATTR, 'Marks a host-written <style> (pageDefaultCss tells authored styles apart by it).')}
${constant('SANDBOX_GRANT', SANDBOX_GRANT, 'The iframe sandbox grant: scripts, never same-origin.')}
${constant('SANDBOX_ALLOW', SANDBOX_ALLOW, 'The iframe allow-list: EMPTY (no microphone, camera, geolocation).')}
${constant('CHAT_HTML_KIT_CSS', CHAT_HTML_KIT_CSS, 'The dream-html class kit.')}
${constant('HEIGHT_BRIDGE', HEIGHT_BRIDGE, 'The chat frame height bridge.')}
${constant('SELECTION_BRIDGE', SELECTION_BRIDGE, 'The text-selection bridge.')}
${constant('REACH_BRIDGE', REACH_BRIDGE, 'The click/keyboard reach bridge.')}
${constant('KIT_BEHAVIOUR', KIT_BEHAVIOUR, 'The kit runtime: tabs and the dc-graph engine.')}
${constant('LINK_GUARD', LINK_GUARD, "The report viewer's link guard.")}
${constant('ZOOM_BRIDGE', ZOOM_BRIDGE, "The report viewer's zoom bridge.")}
${constant('PAGE_DEFAULT_CSS_INSET', pageDefaultCss(true), 'pageDefaultCss(true): page defaults for a report that brings no styles.')}
export { SANDBOX_FONT_CSS };

export interface ServerSandboxSrcdocInput {
  html: string;
  css: string;
  tokens: Record<string, string>;
  scheme?: 'light' | 'dark';
  overrideCss?: string;
  headScript?: string;
}

function hostRootRule(tokens: Record<string, string>, scheme: 'light' | 'dark'): string {
  const rootVars = Object.entries(tokens).map(([token, value]) => \`\${token}: \${value};\`).join(' ');
  return \`:root { color-scheme: \${scheme}; \${rootVars} }\`;
}

/** Mirror of the dashboard's \`buildSandboxSrcdoc\`: CSP meta FIRST, font, tokens, kit, override, head script, body. */
export function buildSandboxSrcdocServer(input: ServerSandboxSrcdocInput): string {
  const { html, css, tokens, scheme = 'light', overrideCss, headScript } = input;
  const parts = [
    '<!doctype html><html><head>',
    \`<meta http-equiv="Content-Security-Policy" content="\${SANDBOX_CSP}">\`,
    '<meta charset="utf-8">',
    \`<style \${HOST_STYLE_ATTR}>\${SANDBOX_FONT_CSS}</style>\`,
    \`<style \${HOST_STYLE_ATTR}>\${hostRootRule(tokens, scheme)}</style>\`,
    \`<style \${HOST_STYLE_ATTR}>\${css}</style>\`,
  ];
  if (overrideCss) parts.push(\`<style \${HOST_STYLE_ATTR}>\${overrideCss}</style>\`);
  if (headScript) parts.push(\`<script>\${headScript}</script>\`);
  parts.push('</head><body>', html);
  parts.push('</body></html>');
  return parts.join('\\n');
}

export interface ServerChatSrcdocInput {
  html: string;
  tokens: Record<string, string>;
  scheme?: 'light' | 'dark';
  overrideCss?: string;
  mode?: 'card' | 'full';
  lang?: string;
}

/** Mirror of the dashboard's \`buildChatSrcdoc\`: a dream-html block as the chat draws it. */
export function buildChatSrcdocServer(input: ServerChatSrcdocInput): string {
  const { html, tokens, scheme = 'light', overrideCss, mode = 'card', lang } = input;
  const doc = buildSandboxSrcdocServer({
    html, css: CHAT_HTML_KIT_CSS, tokens, scheme, overrideCss,
    headScript: \`\${HEIGHT_BRIDGE}
\${SELECTION_BRIDGE}
\${REACH_BRIDGE}
\${KIT_BEHAVIOUR}\`,
  });
  const langAttr = lang ? \` lang="\${lang.replace(/[^a-zA-Z0-9-]/g, '')}"\` : '';
  return doc.replace('<!doctype html><html>', \`<!doctype html><html\${langAttr} data-dc-mode="\${mode}">\`);
}

/** Mirror of the dashboard's \`buildReportSrcdoc\`: a project HTML report page as the file viewer draws it. */
export function buildReportSrcdocServer(html: string, tokens: Record<string, string>, scheme: 'light' | 'dark' = 'light'): string {
  return buildSandboxSrcdocServer({
    html, css: CHAT_HTML_KIT_CSS, tokens, scheme, overrideCss: PAGE_DEFAULT_CSS_INSET,
    headScript: \`\${HEIGHT_BRIDGE}\\n\${SELECTION_BRIDGE}\\n\${LINK_GUARD}\\n\${ZOOM_BRIDGE}\\n\${KIT_BEHAVIOUR}\`,
  });
}
`;
}

export function renderLabKit(): string {
  return `${HEADER('dashboard/src/components/lab/labHtmlKit.ts')}
import { buildSandboxSrcdocServer } from './chat-kit.js';

${constant('LAB_HTML_KIT_CSS', LAB_HTML_KIT_CSS, 'The Lab html/v1 insight class kit.')}
${constant('HTML_HEIGHT_BRIDGE', HTML_HEIGHT_BRIDGE, 'The Lab frame height bridge.')}
/** Mirror of the dashboard's Lab \`buildSrcdoc\`: an html/v1 insight body. */
export function buildLabSrcdocServer(html: string, tokens: Record<string, string>, scheme: 'light' | 'dark' = 'light'): string {
  return buildSandboxSrcdocServer({ html, css: LAB_HTML_KIT_CSS, tokens, scheme, headScript: HTML_HEIGHT_BRIDGE });
}
`;
}

export function renderTokens(tokensCss: string): string {
  const map = (names: readonly string[], theme: 'light' | 'dark') => JSON.stringify(resolveTokensFromCss(tokensCss, names, theme), null, 2);
  return `${HEADER('dashboard/src/styles/tokens.css (resolved var() chains) and ChatPane.css')}
export type KitScheme = 'light' | 'dark';

/** CHAT_KIT_TOKENS resolved per theme: what \`resolveChatKitTokens()\` returns with no scope (report pages). */
export const CHAT_KIT_TOKENS: Record<KitScheme, Record<string, string>> = {
  light: ${map(CHAT_KIT_TOKENS, 'light')},
  dark: ${map(CHAT_KIT_TOKENS, 'dark')},
};

/** The chat pane's reading tokens at zoom 1 (dream-html only; report pages get none). */
export const CHAT_READING_TOKENS: Record<string, string> = ${JSON.stringify(CHAT_READING, null, 2)};

/** HTML_KIT_TOKENS resolved per theme: what the Lab's \`resolveKitTokens()\` returns. */
export const LAB_KIT_TOKENS: Record<KitScheme, Record<string, string>> = {
  light: ${map(HTML_KIT_TOKENS, 'light')},
  dark: ${map(HTML_KIT_TOKENS, 'dark')},
};

/** Tokens for a dream-html block, as the chat pane resolves them. Telegram pictures use light. */
export function chatHtmlTokens(scheme: KitScheme = 'light'): Record<string, string> {
  return { ...CHAT_KIT_TOKENS[scheme], ...CHAT_READING_TOKENS };
}

/** Tokens for a report page (no reading tokens: \`FrameViewer\` resolves without a scope). */
export function reportTokens(scheme: KitScheme = 'light'): Record<string, string> {
  return { ...CHAT_KIT_TOKENS[scheme] };
}

/** Tokens for an html/v1 insight body. */
export function labTokens(scheme: KitScheme = 'light'): Record<string, string> {
  return { ...LAB_KIT_TOKENS[scheme] };
}
`;
}

export const LOCAL_ASSET_SOURCES = ['dashboard/src/components/appLink/viewerPaths.ts', 'dashboard/src/lib/htmlLocalAssets.ts'] as const;

/** The two pure modules, as source: the path rules first, then the inliner minus its import of them. */
export function renderLocalAssets(sources: readonly string[] = LOCAL_ASSET_SOURCES.map((f) => readFileSync(f, 'utf-8'))): string {
  const [paths, assets] = sources;
  const body = assets.replace(/^import \{ parentDir, resolveDocumentRef \} from '[^']+';\n/m, '');
  if (body === assets) throw new Error('htmlLocalAssets.ts no longer imports viewerPaths the way this copy expects');
  return `${HEADER(LOCAL_ASSET_SOURCES.join(' + '))}\n${paths.trimEnd()}\n\n${body}`;
}

export const OUTPUTS = {
  font: 'src/lib/sandbox-font.ts',
  chat: 'src/lib/telegram/chat-kit.ts',
  lab: 'src/lib/telegram/lab-kit.ts',
  tokens: 'src/lib/telegram/kit-tokens.ts',
  assets: 'src/lib/telegram/html-local-assets.ts',
} as const;
export const TOKENS_CSS = 'dashboard/src/styles/tokens.css';

export function renderAll(): Record<keyof typeof OUTPUTS, string> {
  return {
    font: renderFont(),
    chat: renderChatKit(),
    lab: renderLabKit(),
    tokens: renderTokens(readFileSync(TOKENS_CSS, 'utf-8')),
    assets: renderLocalAssets(),
  };
}

// vite-node drops the script path from argv, so "run as a script" is "not under vitest".
if (!process.env.VITEST) {
  const out = renderAll();
  for (const key of Object.keys(OUTPUTS) as (keyof typeof OUTPUTS)[]) {
    writeFileSync(OUTPUTS[key], out[key]);
    console.log(`wrote ${OUTPUTS[key]} (${out[key].length} chars)`);
  }
}

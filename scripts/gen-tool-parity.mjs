#!/usr/bin/env node
/**
 * docs/tool-parity.md, from the row table in docs/tool-parity.json plus the headless envelopes, so
 * what the doc says each tool does cannot drift from the table the code reads. `--check` fails on
 * a stale doc (tool-parity.test.ts runs it).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(join(root, 'docs', 'tool-parity.json'), 'utf-8'));
const envelope = readFileSync(join(root, 'src', 'lib', 't3-bridge', 'headless-envelope.ts'), 'utf-8');
const rows = [...envelope.matchAll(/^\s*'?([a-z-]+)'?: \{ claude: '([^']+)', codex: (null|'[a-z]+'), brain: (?:true|false)(?:, strict: true)?(?:, why: '((?:[^'\\]|\\.)*)')? \},$/gm)];

const MODE = { "'auto'": 'Sandboxed: project and linked repos, no network, approvals declined', "'default'": 'Read-only, approvals declined' };
const lines = [
  '# What runs on which tool',
  '',
  'Generated by `scripts/gen-tool-parity.mjs` from `docs/tool-parity.json` and `src/lib/t3-bridge/headless-envelope.ts`. Do not edit by hand.',
  '',
  '**works** = covered by tests and a real run. **experimental** = built and tested against a fake, not yet proven on a real account. **Claude only** = stays on Claude on purpose.',
  '',
  '## Features',
  '',
  '| Feature | Claude | Codex | Note |',
  '|---|---|---|---|',
  ...data.features.map((f) => `| ${f.name} | ${f.claude} | ${f.codex} | ${f.note ?? ''} |`),
  '',
  '## Unattended surfaces',
  '',
  '| Surface | On Claude | On Codex |',
  '|---|---|---|',
  ...rows.map(([, name, claude, codex, why]) => `| ${name} | ${claude} | ${codex === 'null' ? `Claude only. ${(why ?? '').replace(/\\'/g, "'")}` : MODE[codex]} |`),
  '',
];
const out = lines.join('\n');
const path = join(root, 'docs', 'tool-parity.md');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf-8') !== out) { console.error('docs/tool-parity.md is stale: run node scripts/gen-tool-parity.mjs'); process.exit(1); }
} else {
  writeFileSync(path, out);
}

#!/usr/bin/env node
/**
 * docs/tool-parity.md, from the row table in docs/tool-parity.json plus the headless envelopes, so
 * what the doc says each tool does cannot drift from the table the code reads. `--check` fails on
 * a stale doc (tool-parity.test.ts runs it).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(join(root, 'docs', 'tool-parity.json'), 'utf-8'));
const envelope = readFileSync(join(root, 'src', 'lib', 't3-bridge', 'headless-envelope.ts'), 'utf-8');
const block = envelope.slice(envelope.indexOf('export const HEADLESS_ENVELOPES'), envelope.indexOf('\n};', envelope.indexOf('export const HEADLESS_ENVELOPES')));
/** One field of a row line: a quoted string (escapes kept), null, or a bare word. */
const field = (line, key) => {
  const m = line.match(new RegExp(`\\b${key}: (null|true|false|'((?:[^'\\\\]|\\\\.)*)')`));
  if (!m) return undefined;
  return m[2] !== undefined ? m[2].replace(/\\'/g, "'") : m[1];
};
const rows = [...block.matchAll(/^\s*'?([a-z-]+)'?: \{ (claude: .*) \},$/gm)].map(([, name, rest]) => ({
  name,
  claude: field(rest, 'claude'),
  codex: field(rest, 'codex'),
  antigravity: field(rest, 'antigravity'),
  why: field(rest, 'why'),
  antigravityWhy: field(rest, 'antigravityWhy'),
}));

const EVIDENCE = { real: 'real turn', fake: 'fake agent', code: 'code and tests' };
/** One tool's cell: state, what proves it, and the note or the tool's limit. */
const cell = (c) => [`**${c.state}**${c.when ? ` ${c.when}` : ''} (${EVIDENCE[c.evidence]})`, c.limit ? `Limit: ${c.limit}` : '', c.note ?? ''].filter(Boolean).join('. ').replace(/\.\./g, '.').replace(/\|/g, '/');
const MODE = { auto: 'Sandboxed: project and linked repos, no network, approvals declined', default: 'Read-only: a command is approved only when every program in it reads, anything else declined' };
const AG_MODE = { write: 'Answered by the bridge once its write gate ran; what the gate leaves to the owner is refused', read: 'Read-only: no edits, only plain read commands' };
const lines = [
  '# What runs on which tool',
  '',
  'Generated by `scripts/gen-tool-parity.mjs` from `docs/tool-parity.json` and `src/lib/t3-bridge/headless-envelope.ts`. Do not edit by hand.',
  '',
  '**works** = covered by tests and a real run. **experimental** = built and tested against a fake, not yet proven on a real account. **Claude only** = stays on Claude on purpose.',
  '',
  '## Features',
  '',
  '| Feature | Claude | Codex | Note |',
  '|---|---|---|---|',
  ...data.features.map((f) => `| ${f.name} | ${f.claude} | ${f.codex} | ${f.note ?? ''} |`),
  '',
  '## Unattended surfaces',
  '',
  '| Surface | On Claude | On Codex | On Antigravity |',
  '|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.claude} | ${r.codex === 'null' ? `Claude only. ${r.why ?? ''}` : MODE[r.codex]} | ${r.antigravity === 'null' || r.antigravity === undefined ? `Claude only. ${r.antigravityWhy ?? ''}` : AG_MODE[r.antigravity]} |`),
  '',
  '## Every Claude capability, per tool',
  '',
  'Read from the code by `tests/unit/tool-parity-guard.test.ts`: a hook, skill, skill pack, sub-agent role, dream-view type, chat mode, control request or unattended surface that Claude gains without these two cells is red. **works** = a real turn showed it (date given). **built** = built and proved on a fake agent or in tests, not on a real turn. **partly**, **missing**, **impossible** (the tool\'s own limit is named), **claude-only** (on purpose).',
  '',
  '| Capability | Codex | Antigravity |',
  '|---|---|---|',
  ...data.capabilities.rows.map((r) => `| ${r.what} (${r.ids.length > 3 ? `${r.ids.length} ${r.kind}s` : r.ids.map((id) => `\`${id}\``).join(', ')}) | ${cell(r.codex)} | ${cell(r.antigravity)} |`),
  '',
];
const out = lines.join('\n');
const path = join(root, 'docs', 'tool-parity.md');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf-8') !== out) { console.error('docs/tool-parity.md is stale: run node scripts/gen-tool-parity.mjs'); process.exit(1); }
} else {
  writeFileSync(path, out);
}
